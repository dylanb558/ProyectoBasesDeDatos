
CREATE TABLE Empresa (
  ID_EMPRESA SERIAL PRIMARY KEY,
  NOMBRE TEXT NOT NULL,
  RUT_OPE TEXT UNIQUE,
  RUT_PLA TEXT UNIQUE,
  RUT_PE  TEXT UNIQUE
);

CREATE TABLE Gerencia_Operaciones (
  RUT_OPE TEXT PRIMARY KEY,
  FOREIGN KEY (RUT_OPE) REFERENCES Empresa(RUT_OPE)
);

CREATE TABLE Gerencia_Planificacion (
  RUT_PLA TEXT PRIMARY KEY,
  FOREIGN KEY (RUT_PLA) REFERENCES Empresa(RUT_PLA)
);

CREATE TABLE Gerencia_Personas (
  RUT_PE TEXT PRIMARY KEY,
  FOREIGN KEY (RUT_PE) REFERENCES Empresa(RUT_PE)
);


CREATE TABLE Tipo_Area_Operaciones (
  TIPO_AREA TEXT PRIMARY KEY,
  NOMBRE_AREA TEXT NOT NULL
);

CREATE TABLE Area_Operaciones (
  RUT_OPE TEXT NOT NULL,
  TIPO_AREA TEXT NOT NULL,
  PRIMARY KEY (RUT_OPE, TIPO_AREA),
  FOREIGN KEY (RUT_OPE) REFERENCES Gerencia_Operaciones(RUT_OPE),
  FOREIGN KEY (TIPO_AREA) REFERENCES Tipo_Area_Operaciones(TIPO_AREA)
);


CREATE TABLE Tipo_Area_Planificacion (
  TIPO_AREA TEXT PRIMARY KEY,
  NOMBRE_AREA TEXT NOT NULL
);

CREATE TABLE Area_Planificacion (
  RUT_PLA TEXT NOT NULL,
  TIPO_AREA TEXT NOT NULL,
  PRIMARY KEY (RUT_PLA, TIPO_AREA),
  FOREIGN KEY (RUT_PLA) REFERENCES Gerencia_Planificacion(RUT_PLA),
  FOREIGN KEY (TIPO_AREA) REFERENCES Tipo_Area_Planificacion(TIPO_AREA)
);


CREATE TABLE Tipo_Area_Personas (
  TIPO_AREA TEXT PRIMARY KEY,
  NOMBRE_AREA TEXT NOT NULL
);

CREATE TABLE Area_Personas (
  RUT_PE TEXT NOT NULL,
  TIPO_AREA TEXT NOT NULL,
  PRIMARY KEY (RUT_PE, TIPO_AREA),
  FOREIGN KEY (RUT_PE) REFERENCES Gerencia_Personas(RUT_PE),
  FOREIGN KEY (TIPO_AREA) REFERENCES Tipo_Area_Personas(TIPO_AREA)
);




CREATE TABLE Trabajador_Operaciones (
  RUT TEXT PRIMARY KEY,
  NOMBRE TEXT NOT NULL,
  CARGO TEXT NOT NULL
);

CREATE TABLE Trabaja (
  RUT TEXT NOT NULL,
  RUT_OPE TEXT NOT NULL,   -
  TIPO_AREA TEXT NOT NULL,
  PRIMARY KEY (RUT, RUT_OPE, TIPO_AREA),
  FOREIGN KEY (RUT) REFERENCES Trabajador_Operaciones(RUT),
  FOREIGN KEY (RUT_OPE, TIPO_AREA)
    REFERENCES Area_Operaciones(RUT_OPE, TIPO_AREA)
);